"""Банк предложений на перевод (RU → EN), привязанных к урокам грамматики.

Зачем: в уроках всего по 1–2 предложения на перевод, и в 5-минутке они
повторялись снова и снова. Здесь по 7–9 предложений на каждый урок, темы
вперемешку: быт, путешествия, работа. Бот выдаёт их только по урокам, которые
ты уже начал, и сначала те, что давно (или ещё ни разу) не попадались.

Как писать варианты ответа — шаблоном с фигурными скобками:
  "I {like|love} {cooking|to cook}."  →  4 допустимых ответа;
  "{|Right now, }I'm working"         →  пустой вариант = «можно без этого».
Первый вариант из каждой скобки — «эталон», его бот покажет при ошибке.
Сокращения (don't = do not, I'm = I am) и регистр проверка сама учитывает,
писать оба варианта не нужно. Исключение: she's/he's/it's бот читает как
«is», поэтому для Present Perfect пиши «{She has|She's}».

Ключ вопроса: "tr.<id урока>:<номер>". Новые предложения добавляй В КОНЕЦ
списка урока, не переставляй старые — по номеру хранятся ошибки.
"""
import itertools
import re

from bot.content.grammar import Question, text

TR_PREFIX = "tr."

_GROUP_RE = re.compile(r"\{([^{}]*)\}")


def expand(pattern: str) -> list[str]:
    """Раскрывает шаблон "I {like|love} it" в ["I like it", "I love it"]."""
    parts = _GROUP_RE.split(pattern)
    # split с группой даёт: [текст, варианты, текст, варианты, ..., текст]
    choices = [[p] if i % 2 == 0 else p.split("|") for i, p in enumerate(parts)]
    result = []
    for combo in itertools.product(*choices):
        s = re.sub(r"\s+", " ", "".join(combo)).strip()
        s = re.sub(r"\s+([,.?!])", r"\1", s)
        result.append(s[:1].upper() + s[1:])
    return list(dict.fromkeys(result))


def tr(ru: str, patterns: str | list[str], explain: str) -> Question:
    if isinstance(patterns, str):
        patterns = [patterns]
    answers = [a for p in patterns for a in expand(p)]
    return text(f"Переведи: {ru}", answers, explain)


